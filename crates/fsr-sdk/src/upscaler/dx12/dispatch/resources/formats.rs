// Fixed backend interpretations, not a caller-selected view override. The native
// surface enum alone cannot distinguish ordinary R32F from the depth plane.
pub(super) fn depth_views(format: DXGI_FORMAT) -> Option<(DXGI_FORMAT, DXGI_FORMAT, bool)> {
    match format {
        DXGI_FORMAT_R32_TYPELESS | DXGI_FORMAT_D32_FLOAT => Some((
            DXGI_FORMAT_D32_FLOAT,
            DXGI_FORMAT_R32_FLOAT,
            format == DXGI_FORMAT_D32_FLOAT,
        )),
        DXGI_FORMAT_R32G8X24_TYPELESS | DXGI_FORMAT_D32_FLOAT_S8X24_UINT => Some((
            DXGI_FORMAT_D32_FLOAT_S8X24_UINT,
            DXGI_FORMAT_R32_FLOAT_X8X24_TYPELESS,
            format == DXGI_FORMAT_D32_FLOAT_S8X24_UINT,
        )),
        DXGI_FORMAT_D16_UNORM => Some((DXGI_FORMAT_D16_UNORM, DXGI_FORMAT_R16_UNORM, true)),
        DXGI_FORMAT_R24G8_TYPELESS | DXGI_FORMAT_D24_UNORM_S8_UINT => Some((
            DXGI_FORMAT_D24_UNORM_S8_UINT,
            DXGI_FORMAT_R24_UNORM_X8_TYPELESS,
            format == DXGI_FORMAT_D24_UNORM_S8_UINT,
        )),
        _ => None,
    }
}

// The SDK fixes these typed views from the actual allocation, irrespective of
// caller-created views. R16_TYPELESS is FLOAT even when its flags permit a DSV.
pub(super) fn fixed_view(format: DXGI_FORMAT) -> Option<DXGI_FORMAT> {
    Some(match format {
        DXGI_FORMAT_R32G32B32A32_TYPELESS => DXGI_FORMAT_R32G32B32A32_FLOAT,
        DXGI_FORMAT_R16G16B16A16_TYPELESS => DXGI_FORMAT_R16G16B16A16_FLOAT,
        DXGI_FORMAT_R10G10B10A2_TYPELESS => DXGI_FORMAT_R10G10B10A2_UNORM,
        DXGI_FORMAT_R8G8B8A8_TYPELESS => DXGI_FORMAT_R8G8B8A8_UNORM,
        DXGI_FORMAT_B8G8R8A8_TYPELESS => DXGI_FORMAT_B8G8R8A8_UNORM,
        DXGI_FORMAT_R32G32B32_TYPELESS | DXGI_FORMAT_R32G32B32_FLOAT => DXGI_FORMAT_R32G32B32_FLOAT,
        DXGI_FORMAT_R32G32_TYPELESS => DXGI_FORMAT_R32G32_FLOAT,
        DXGI_FORMAT_R16G16_TYPELESS => DXGI_FORMAT_R16G16_FLOAT,
        DXGI_FORMAT_R32_TYPELESS => DXGI_FORMAT_R32_FLOAT,
        DXGI_FORMAT_R16_TYPELESS => DXGI_FORMAT_R16_FLOAT,
        DXGI_FORMAT_R8_TYPELESS => DXGI_FORMAT_R8_UNORM,
        DXGI_FORMAT_R8G8B8A8_SNORM | DXGI_FORMAT_R9G9B9E5_SHAREDEXP | DXGI_FORMAT_R16_UNORM => {
            format
        }
        _ => return None,
    })
}

